'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {createObservationArchive}=require('../js/identity-archive.js');
const {canonicalJSON,sha256Text}=require('../js/enrichment-canonical.js');
const root=path.join(__dirname,'../fixtures/c01/maven-central');
test('T58-T61 genuine archived Maven Central JUnit 4.13.2 observation replays offline',async()=>{
 const raw=fs.readFileSync(path.join(root,'junit-4.13.2.observation.json'),'utf8').trimEnd();
 const ref=JSON.parse(fs.readFileSync(path.join(root,'junit-4.13.2.reference.json'),'utf8'));
 const archive=createObservationArchive({get:async id=>id===ref.id?raw:null,put:async()=>{throw Error('offline replay is read-only');}});
 const result=await archive.load(ref);
 assert.equal(ref.sha256,sha256Text(raw));
 assert.equal(ref.id,'observation:'+ref.sha256);
 assert.equal(result.providerId,'maven-central');
 assert.equal(result.url,'https://repo.maven.apache.org/maven2/junit/junit/4.13.2/junit-4.13.2.pom');
 assert.equal(result.status,200);
 assert.equal(result.transport,'ok');
 assert.equal(result.query.namespace,'junit');
 assert.equal(result.query.name,'junit');
 assert.equal(result.query.version,'4.13.2');
 assert.equal(sha256Text(result.body),ref.contentHash);
 assert.match(result.body,/<groupId>junit<\/groupId>/);
 assert.match(result.body,/<artifactId>junit<\/artifactId>/);
 assert.match(result.body,/<version>4\.13\.2<\/version>/);
 assert.equal(canonicalJSON(await archive.load(ref)),canonicalJSON(result));
 await assert.rejects(archive.load({id:'observation:'+'0'.repeat(64)}),/integrity/);
 const corrupted=raw.replace('junit','tampered');
 const corruptArchive=createObservationArchive({get:async()=>corrupted,put:async()=>{}});
 await assert.rejects(corruptArchive.load(ref),/integrity/);
});
